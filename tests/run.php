foreach ($dirs as $file => $dir) {
    $t = parsed($file);
    $d = data($file);
    check("$file: _scalerType", true, $t->_scalerType);
    check("$file: table count", count($dir), count($t->_table));
    check("$file: numTables in offset table", count($dir), unpack('n', substr($d, 4, 2))[1]);
    check("$file: tags", array_map('strval', array_keys($dir)), array_map(function($x) { return $x['tag']; }, $t->_table));
    $expectDump = '';
    foreach (array_values($t->_table) as $i => $e) {
        $tag = $e['tag'];
        if (! isset($dir[$tag])) {
            continue;
        }
        check("$file $tag: keys", array('tag', 'checkSum', 'offset', 'length'), array_keys($e));
        check("$file $tag: offset", $dir[$tag][0], $e['offset']);
        check("$file $tag: length", $dir[$tag][1], $e['length']);
        check("$file $tag: offset aligned", 0, $e['offset'] % 4);
        $body = substr($d, $dir[$tag][0], $dir[$tag][1]);
        check("$file $tag: checkSum", tableChecksum($body, $tag === 'head'), $e['checkSum']);
        $expectDump .= "tag:$tag checkSum:".tableChecksum($body, $tag === 'head')." offset:{$dir[$tag][0]} length:{$dir[$tag][1]}\n";
    }
    check("$file: dump", $expectDump, dumped($t));
}
