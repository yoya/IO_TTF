function data($name) {
    return file_get_contents(dirname(__FILE__).'/data/'.$name);
}
function parsed($name) {
    $t = new IO_TTF();
    $t->parse(data($name));
    return $t;
}
function dumped($t) {
    ob_start();
    $t->dump();
    return ob_get_clean();
}
// table checksum (OpenType spec): sum of big endian uint32, zero padded
function tableChecksum($body, $isHead) {
    if ($isHead) {
        $body = substr_replace($body, "\0\0\0\0", 8, 4); // checkSumAdjustment
    }
    $body .= str_repeat("\0", (4 - strlen($body) % 4) % 4);
    $sum = 0;
    foreach (unpack('N*', $body) as $v) {
        $sum = ($sum + $v) & 0xffffffff;
    }
    return $sum;
}
