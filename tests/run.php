$dirs = array(
    'minimal.ttf' => array('cmap' => array(172, 36), 'cvt ' => array(208, 6), 'glyf' => array(216, 0),
                           'head' => array(216, 54), 'hhea' => array(272, 36), 'hmtx' => array(308, 4),
