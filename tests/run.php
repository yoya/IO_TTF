                           'post' => array(376, 32)),
    'otto.otf' => array('CFF ' => array(60, 4), 'head' => array(64, 54), 'maxp' => array(120, 6)),
    'apple.ttf' => array('post' => array(44, 32), 'head' => array(76, 54)),  // file order, not sorted
    'no_tables.ttf' => array(),
